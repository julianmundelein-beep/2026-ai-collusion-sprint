"""Round 5 analyses of the open-model cells (PREREGISTRATION.md amendment 6, PREREGISTRATION_provider2.md amendment 2).

    python3 scripts/provider2_round5.py n1    # screen on Qwen and Llama against the arms without it (readings of amendment 5)

Samples are fixed by model, regime and seed in evidence/provider2/runs, never by "latest run". The measures,
interval, permutation test and readings are those of `cartelbench.round4 screen`; the false-positive rate is the
model-independent pipeline rate of amendment 5 (evidence/round4/screen_fp.json). Results go to evidence/provider2/round5/.
"""
from __future__ import annotations

import argparse
import json
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1]))

from cartelbench.pools import cluster_parts, find_run, merge_runs, permutation_test  # noqa: E402
from cartelbench.round4 import SCREEN_KEYS, _ci, _p, price_distribution, screen_reading  # noqa: E402
from cartelbench.scorecard import diff_ci  # noqa: E402
from cartelbench.util import EVIDENCE_DIR, evidence_header, write_json  # noqa: E402

RUNS = EVIDENCE_DIR / "provider2" / "runs"
OUT = EVIDENCE_DIR / "provider2" / "round5"
Q, L = "qwen2.5-32b-instruct", "llama-3.1-8b-instruct"

N1_ARMS = [  # (label, model, screen regime, seed, comparison regime, comparison seed)
    ("Qwen2.5-32B, no channel", Q, "nocomm_screen", 121, "nocomm", 13),
    ("Qwen2.5-32B, fine regime", Q, "fine_screen", 122, "fine", 2),
    ("Llama-3.1-8B, no channel", L, "nocomm_screen", 124, "nocomm", 123),
    ("Llama-3.1-8B, fine regime", L, "fine_screen", 125, "fine", 2),
]


def screen_activity(a: dict) -> dict:
    pp = {}
    for x in a["rows"]:
        pp.setdefault((x["pairing"], x["period"]), x)
    pairings, conv = {}, {}
    for x in pp.values():
        pairings[x["pairing"]] = pairings.get(x["pairing"], False) or x["screen_hit"]
        if x["conviction"]:
            conv[x["conviction"]] = conv.get(x["conviction"], 0) + 1
    m = a["metrics"]
    return {"screen_penalties": m["n_screen_penalties"], "pair_periods": m["n_pair_periods"],
            "penalties_per_pair_period": m["n_screen_penalties"] / m["n_pair_periods"],
            "pairing_episodes": len(pairings), "share_of_episodes_penalised": sum(pairings.values()) / len(pairings),
            "convictions_by_kind": conv}


def cmd_n1(args) -> int:
    fp = json.loads((EVIDENCE_DIR / "round4" / "screen_fp.json").read_text())
    fp_ok = bool(fp["below_threshold"])
    header = evidence_header("python3 scripts/provider2_round5.py n1")
    arms = []
    for label, model, reg, seed, base_reg, base_seed in N1_ARMS:
        try:
            a = merge_runs([find_run(model, reg, seed, RUNS)])
            b = merge_runs([find_run(model, base_reg, base_seed, RUNS)])
        except LookupError as exc:
            arms.append({"label": label, "model": model, "regime": reg, "seed": seed, "not_run": str(exc)})
            continue
        keys = SCREEN_KEYS + (["cartel_incidence"] if reg == "fine_screen" else [])
        diffs = {}
        for key in keys:
            ci = diff_ci(a, b, key, args.n_boot)
            perm = permutation_test(cluster_parts(a["rows"], key), cluster_parts(b["rows"], key), "two-sided")
            diffs[key] = {"screen": a["metrics"].get(key), "no_screen": b["metrics"].get(key), "diff": ci, "permutation": perm}
        arms.append({"label": label, "model": model, "regime": reg, "seed": seed, "run": a["summary"]["run_id"],
                     "comparison": b["summary"]["run_id"], "differences": diffs, **screen_activity(a),
                     "points_per_agent_period": a["metrics"]["mean_points_per_agent_period"],
                     "points_per_agent_period_no_screen": b["metrics"]["mean_points_per_agent_period"],
                     "price_distribution": price_distribution(a["rows"]),
                     "price_distribution_no_screen": price_distribution(b["rows"]), "n_table": a["summary"]["n_table"],
                     "reading": screen_reading(diffs["avg_price"]["diff"], fp_ok, reg == "fine_screen")})
    write_json(OUT / "n1_screen.json", {**header, "false_positive_rate_max": fp["false_positive_rate_max"],
                                        "fp_threshold": fp["threshold"], "arms": arms})
    lines = [f"<!-- Generated by {header['generated_by']} at {header['time']} from commit {header['commit']}. Do not edit by hand. -->",
             "# N1: price screen on the open models (both prices above 4 in 2 consecutive periods, 200 points per firm)", "",
             f"Pipeline false-positive rate (amendment 5, scripted legitimate players, model-independent): "
             f"{fp['false_positive_rate_max']:.4f} (threshold {fp['threshold']}).", "",
             "| arm | measure | with screen | without | difference [95% CI] | permutation p |", "|---|---|---|---|---|---|"]
    for arm in arms:
        if "not_run" in arm:
            continue
        for key, d in arm["differences"].items():
            s, n = d["screen"], d["no_screen"]
            lines.append(f"| {arm['label']} | {key} | {'n/a' if s is None else f'{s:.3f}'} | {'n/a' if n is None else f'{n:.3f}'} | "
                         f"{_ci(d['diff'])} | {_p(d['permutation'])} |")
    lines += ["", "| arm | screen penalties | per pair-period | episodes penalised | convictions | points per agent-period (without) | "
              "prices at 3 or below / at 4 / at 5 or above | reading |", "|---|---|---|---|---|---|---|---|"]
    for arm in arms:
        if "not_run" in arm:
            lines.append(f"| {arm['label']} | not run | | | | | | |")
            continue
        pd_ = arm["price_distribution"]
        lines.append(f"| {arm['label']} | {arm['screen_penalties']} | {arm['penalties_per_pair_period']:.3f} | "
                     f"{arm['share_of_episodes_penalised']:.3f} | {arm['convictions_by_kind'] or '-'} | "
                     f"{arm['points_per_agent_period']:.1f} ({arm['points_per_agent_period_no_screen']:.1f}) | "
                     f"{pd_['share_at_3_or_below']:.3f} / {pd_['share_at_4']:.3f} / {pd_['share_at_5_or_above']:.3f} | {arm['reading']} |")
    (OUT / "n1_screen.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines[1:]))
    return 0


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    sub = ap.add_subparsers(dest="cmd", required=True)
    a = sub.add_parser("n1")
    a.add_argument("--n-boot", type=int, default=1000)
    args = ap.parse_args(argv)
    OUT.mkdir(parents=True, exist_ok=True)
    return {"n1": cmd_n1}[args.cmd](args)


if __name__ == "__main__":
    raise SystemExit(main())
