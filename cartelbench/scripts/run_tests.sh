#!/bin/sh
# Runs the test suite and records the result as evidence (evidence/tests/pytest_latest.txt).
set -u
cd "$(dirname "$0")/.." || exit 1
mkdir -p evidence/tests
out=evidence/tests/pytest_latest.txt
{
  echo "Generated by sh cartelbench/scripts/run_tests.sh at $(date -u +%Y-%m-%dT%H:%M:%SZ) from commit $(git rev-parse HEAD). Do not edit by hand."
  python3 -m pytest tests -q 2>&1
} > "$out"
tail -1 "$out"
grep -q " passed" "$out" && ! grep -q "failed" "$out"
